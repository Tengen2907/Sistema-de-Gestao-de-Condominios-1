    public void Cunsulta_Funcionarios() {
        DefaultTableModel model = (DefaultTableModel) tblFuncionarios.getModel();
        model.setRowCount(0);
        Vector l = PainelCadastroFuncionario.ler_texto();
        for (int i = 0; i < l.size(); i++) {
            Funcionario f = (Funcionario) l.get(i);
            model.addRow(new Object[]{
                f.getId(), f.getNomeCompleto(), f.getCargo(), f.getTelefone(),
                f.getSalario()});
        }
    }

    public void procurar() {
        String id = txtID.getText().trim();
        Vector l = PainelCadastroFuncionario.ler_texto();
        for (int i = 0; i < l.size(); i++) {
            Funcionario f = (Funcionario) l.get(i);
            if (id.equals(f.getId() + "")) {
                lblNome.setText(f.getNomeCompleto());
                lblSalario.setText(f.getSalario() + " MZN");
                lblCargo.setText(f.getCargo());
                return;
            }
        }
        JOptionPane.showMessageDialog(null, "Funcionario nao encontrado");
    }

    public void pagar() {

        try {
            String id = txtID.getText().trim();
            double novoSalario = Double.parseDouble(txtNovoSalario.getText().trim());
            if (novoSalario <= 0) {
                JOptionPane.showMessageDialog(null, "Novo salario invalido");
                return;
            }
            
            Vector l = PainelCadastroFuncionario.ler_texto();
            Funcionario alvo=null;
            double salarioAnterior = 0;
            
            for (int i = 0; i < l.size(); i++) {
                Funcionario f = (Funcionario) l.get(i);
                if (id.equals(f.getId() + "")) {
                    alvo= f;
                    salarioAnterior=f.getSalario();
                }
            }
            if (alvo == null) {
                JOptionPane.showMessageDialog(null, "Funcionario nao encontrado");
                return;
            }

            if (novoSalario == salarioAnterior) {
                JOptionPane.showMessageDialog(null, "O novo salario e igual ao actual");
                return;
            }

            alvo.setSalario(novoSalario);
            PainelCadastroFuncionario.guardar_texto(l);
            
            String tipo;
            if (novoSalario > salarioAnterior) {
                tipo = "Aumento";
            } else {
                tipo = "Reducao";
            }

            JOptionPane.showMessageDialog(null, tipo + " confirmado: " + salarioAnterior + " -> " + novoSalario + " MZN");
            txtNovoSalario.setText("");
            procurar();
            Cunsulta_Funcionarios();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Novo salario invalido");
        }catch(Exception e){
            JOptionPane.showMessageDialog(null, "Falha ao actuaaliza o salario");
            e.printStackTrace();
        }
    }

